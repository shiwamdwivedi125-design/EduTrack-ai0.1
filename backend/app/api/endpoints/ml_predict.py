"""ML Prediction endpoint"""
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from app.database.session import get_db
from app.models import User, Student, Marks, Attendance, StudentSemester
from app.core.security import get_current_user
import os

router = APIRouter()
MODEL_DIR = os.path.join(os.path.dirname(__file__), "..", "..", "..", "ml_models")


def load_model():
    try:
        import joblib
        model_path = os.path.join(MODEL_DIR, "performance_model.pkl")
        if os.path.exists(model_path):
            return joblib.load(model_path)
    except Exception:
        pass
    return None


def rule_based_predict(features: dict) -> dict:
    """Fallback rule-based prediction when ML model unavailable"""
    attendance = features.get("attendance", 75)
    cgpa = features.get("previous_cgpa", 6.0)
    internal = features.get("avg_internal_percentage", 60)
    
    score = 0
    if attendance >= 85:
        score += 30
    elif attendance >= 75:
        score += 20
    elif attendance >= 65:
        score += 10

    if cgpa >= 8.0:
        score += 35
    elif cgpa >= 7.0:
        score += 25
    elif cgpa >= 6.0:
        score += 15
    elif cgpa >= 5.0:
        score += 5

    if internal >= 80:
        score += 35
    elif internal >= 65:
        score += 25
    elif internal >= 50:
        score += 15

    probability = round(score / 100, 2)
    prediction = "Pass" if probability >= 0.5 else "Needs Improvement"

    return {
        "prediction": prediction,
        "probability": probability,
        "confidence": "moderate",
        "model_type": "rule-based-fallback",
        "disclaimer": "This prediction is generated by a rule-based algorithm and is for guidance only. It does not determine student outcomes."
    }


@router.post("/predict")
async def predict_performance(
    payload: dict,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Predict student academic performance.
    DISCLAIMER: Predictions are estimates only, not automated outcome determiners.
    """
    student_id = payload.get("student_id")
    
    # Build features from DB if student_id provided
    if student_id:
        # Attendance
        att_records = db.query(Attendance).filter(Attendance.student_id == student_id).all()
        total = len(att_records)
        present = sum(1 for a in att_records if a.is_present)
        att_pct = round((present / total) * 100, 2) if total > 0 else 75

        # CGPA
        sems = db.query(StudentSemester).filter(StudentSemester.student_id == student_id).all()
        cgpa = sems[-1].cgpa if sems else payload.get("previous_cgpa", 6.0)

        # Internal marks avg
        marks = db.query(Marks).filter(Marks.student_id == student_id).all()
        avg_int = round(sum(m.internal_marks for m in marks) / len(marks), 2) if marks else 15
        max_int = round(sum(m.internal_marks for m in marks) / sum(30 for _ in marks) * 100, 2) if marks else 60

        features = {
            "attendance": att_pct,
            "previous_cgpa": cgpa,
            "avg_internal_percentage": max_int,
        }
    else:
        features = {
            "attendance": float(payload.get("attendance", 75)),
            "previous_cgpa": float(payload.get("previous_cgpa", 6.0)),
            "avg_internal_percentage": float(payload.get("avg_internal_percentage", 60)),
        }

    # Try ML model first
    model = load_model()
    if model:
        try:
            import numpy as np
            X = [[features["attendance"], features["previous_cgpa"], features["avg_internal_percentage"]]]
            pred = model.predict(X)[0]
            proba = model.predict_proba(X)[0]
            return {
                "prediction": "Pass" if pred == 1 else "Needs Improvement",
                "probability": round(float(max(proba)), 2),
                "features_used": features,
                "model_type": "ml-random-forest",
                "disclaimer": "This prediction is generated by an ML model trained on synthetic data and is for guidance only.",
            }
        except Exception as e:
            pass

    result = rule_based_predict(features)
    result["features_used"] = features
    return result


@router.get("/evaluation")
async def model_evaluation(current_user: User = Depends(get_current_user)):
    """Get ML model evaluation metrics"""
    eval_path = os.path.join(MODEL_DIR, "evaluation.json")
    if os.path.exists(eval_path):
        import json
        with open(eval_path) as f:
            return json.load(f)
    
    return {
        "status": "Model not yet trained",
        "message": "Run scripts/train_ml.py to train the model",
        "note": "Model requires sufficient training data. Currently using rule-based fallback.",
        "disclaimer": "ML predictions are estimates only."
    }


